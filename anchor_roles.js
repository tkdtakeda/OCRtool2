/* ════════════════════════════════════════════════════════
   anchor_roles.js  目印（アンカー）の役割
   Responsibility: 役割の正規化と判定のみ。DOM・OpenCV 非依存（単体テスト可能）
   ────────────────────────────────────────────────────────
   帳票判定（どの帳票か）と位置合わせ（傾き・倍率・平行移動）では、目印に求める性質が
   食い違う。
   ─ 判定用: 他の帳票と見分けが付くこと。広く特徴的な範囲ほど有利。
             ページ内のどこで一致したかは問わない（スコアの高さだけを見るため）。
   ─ 位置合わせ用: 同じページ内で一意で、位置が正確に決まること。狭く輪郭のはっきりした
             範囲ほど有利。広い範囲は、ページ内の局所的な印刷ズレ（罫線幅の微差・紙送りの
             個体差等）を平均した「妥協点」に一致しやすく、スコアは高くても位置がぶれる。
   このため「判定を良くするために目印を足したら位置合わせが悪化する」が実際に起こる。
   役割を明示して、各工程が自分に必要な目印だけを使えるようにする。
   ════════════════════════════════════════════════════════ */
'use strict';

const AnchorRoles = (() => {

  const BOTH = 'both', CLASSIFY = 'classify', ALIGN = 'align';

  /** 役割を正規化する。role 未設定の既存データは旧フラグ alignOnly から解釈し、
      どちらも無い（最初期の）データは従来通り両方に使う＝挙動を変えない。 */
  function roleOf(a) {
    const r = a && a.role;
    if (r === CLASSIFY || r === ALIGN || r === BOTH) return r;
    return (a && a.alignOnly) ? ALIGN : BOTH;
  }

  const usedForClassify = a => roleOf(a) !== ALIGN;
  const usedForAlign    = a => roleOf(a) !== CLASSIFY;

  const LABEL = {
    [BOTH]:     '判定＋位置合わせ',
    [CLASSIFY]: '帳票判定のみ',
    [ALIGN]:    '位置合わせのみ',
  };
  /** 選択肢の説明（UI のツールチップ用） */
  const HINT = {
    [BOTH]:     '両方に使います。目印が少ないうちはこれで十分です。',
    [CLASSIFY]: '「どの帳票か」の判定にだけ使い、位置合わせには使いません。他の帳票と見分けるための広い目印は、位置がぶれやすく位置合わせを悪くするため、こちらにします。',
    [ALIGN]:    '位置合わせにだけ使い、帳票判定には使いません。狭く正確な目印や、他の帳票にも似た形がある目印はこちらにします。判定処理も軽くなります。',
  };

  return { BOTH, CLASSIFY, ALIGN, roleOf, usedForClassify, usedForAlign, LABEL, HINT };

})();
